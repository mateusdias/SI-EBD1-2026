CREATE OR REPLACE VIEW vw_saldo_medicamentos AS
SELECT m.medicamento_id,m.nome,m.apresentacao,m.estoque_minimo,
       NVL(SUM(CASE WHEN l.validade >= TRUNC(SYSDATE)
                    THEN l.quantidade_disponivel ELSE 0 END),0) saldo_utilizavel,
       NVL(SUM(CASE WHEN l.validade < TRUNC(SYSDATE)
                    THEN l.quantidade_disponivel ELSE 0 END),0) saldo_vencido
FROM medicamentos m LEFT JOIN lotes l ON l.medicamento_id=m.medicamento_id
GROUP BY m.medicamento_id,m.nome,m.apresentacao,m.estoque_minimo;

CREATE OR REPLACE VIEW vw_alertas_estoque AS
SELECT m.nome,l.codigo_lote,l.validade,l.quantidade_disponivel,
       CASE WHEN l.validade < TRUNC(SYSDATE) THEN 'VENCIDO'
            WHEN l.validade <= TRUNC(SYSDATE)+30 THEN 'VENCE EM 30 DIAS'
            ELSE 'REGULAR' END alerta
FROM lotes l JOIN medicamentos m ON m.medicamento_id=l.medicamento_id
WHERE l.quantidade_disponivel>0;

