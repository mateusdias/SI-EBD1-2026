  v_item NUMBER; v_prof NUMBER; v_antes NUMBER; v_depois NUMBER;
BEGIN
  SELECT item_id INTO v_item FROM itens_solicitacao
   WHERE medicamento_id=1 AND ROWNUM=1;
  SELECT profissional_id INTO v_prof FROM profissionais WHERE ROWNUM=1;
  BEGIN
    pkg_farmacia.pr_dispensar(v_item,v_prof,9999);
    DBMS_OUTPUT.PUT_LINE('ERRO: teste de excesso deveria falhar');
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('OK: excesso rejeitado: '||SQLERRM);
  END;
  BEGIN
    pkg_farmacia.pr_receber_lote(1,'NF-VENCIDA',1,'LOTE-VENCIDO-NOVO',
                                 TRUNC(SYSDATE)-1,5,3.00);
    DBMS_OUTPUT.PUT_LINE('ERRO: recebimento vencido deveria falhar');
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('OK: recebimento vencido rejeitado: '||SQLERRM);
  END;
  BEGIN
    UPDATE movimentacoes SET referencia='ALTERADO' WHERE movimentacao_id=1;
    DBMS_OUTPUT.PUT_LINE('ERRO: movimentacao nao poderia mudar');
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('OK: historico protegido: '||SQLERRM);
  END;
  v_antes:=pkg_farmacia.fn_saldo_utilizavel(1);
  v_depois:=pkg_farmacia.fn_saldo_utilizavel(1);
  DBMS_OUTPUT.PUT_LINE('Saldo inalterado pelos testes negativos: '||v_antes||' / '||v_depois);
  COMMIT;
END;
