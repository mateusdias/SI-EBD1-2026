CREATE OR REPLACE PACKAGE pkg_farmacia AS
  FUNCTION fn_saldo_utilizavel(p_medicamento_id IN NUMBER) RETURN NUMBER;
  FUNCTION fn_custo_atendimento(p_atendimento_id IN NUMBER) RETURN NUMBER;
  PROCEDURE pr_receber_lote(
    p_fornecedor_id IN NUMBER,p_documento IN VARCHAR2,
    p_medicamento_id IN NUMBER,p_codigo_lote IN VARCHAR2,
    p_validade IN DATE,p_quantidade IN NUMBER,p_custo_unitario IN NUMBER);
  PROCEDURE pr_dispensar(
    p_item_id IN NUMBER,p_profissional_id IN NUMBER,p_quantidade IN NUMBER);
  PROCEDURE pr_relatorio_vencimentos(p_dias IN NUMBER DEFAULT 30);
END pkg_farmacia;
/
CREATE OR REPLACE PACKAGE BODY pkg_farmacia AS
  FUNCTION fn_saldo_utilizavel(p_medicamento_id IN NUMBER) RETURN NUMBER IS
    v_saldo NUMBER;
  BEGIN
    SELECT NVL(SUM(quantidade_disponivel),0) INTO v_saldo FROM lotes
     WHERE medicamento_id=p_medicamento_id AND validade>=TRUNC(SYSDATE);
    RETURN v_saldo;
  END;

  FUNCTION fn_custo_atendimento(p_atendimento_id IN NUMBER) RETURN NUMBER IS
    v_custo NUMBER;
  BEGIN
    SELECT NVL(SUM(d.quantidade*l.custo_unitario),0) INTO v_custo
      FROM solicitacoes s
      JOIN itens_solicitacao i ON i.solicitacao_id=s.solicitacao_id
      JOIN dispensacoes d ON d.item_id=i.item_id
      JOIN lotes l ON l.lote_id=d.lote_id
     WHERE s.atendimento_id=p_atendimento_id;
    RETURN v_custo;
  END;

  PROCEDURE pr_receber_lote(
    p_fornecedor_id IN NUMBER,p_documento IN VARCHAR2,
    p_medicamento_id IN NUMBER,p_codigo_lote IN VARCHAR2,
    p_validade IN DATE,p_quantidade IN NUMBER,p_custo_unitario IN NUMBER) IS
    v_recebimento_id NUMBER; v_lote_id NUMBER;
  BEGIN
    SAVEPOINT sp_receber;
    IF p_quantidade IS NULL OR p_quantidade<=0 OR
       p_custo_unitario IS NULL OR p_custo_unitario<0 OR
       p_validade IS NULL OR p_validade<TRUNC(SYSDATE) THEN
      RAISE_APPLICATION_ERROR(-20001,'Recebimento com dados invalidos ou validade vencida');
    END IF;
    INSERT INTO recebimentos(fornecedor_id,documento)
    VALUES (p_fornecedor_id,p_documento)
    RETURNING recebimento_id INTO v_recebimento_id;
    INSERT INTO lotes(medicamento_id,recebimento_id,codigo_lote,validade,
                      custo_unitario,quantidade_inicial,quantidade_disponivel)
    VALUES (p_medicamento_id,v_recebimento_id,p_codigo_lote,TRUNC(p_validade),
            p_custo_unitario,p_quantidade,p_quantidade)
    RETURNING lote_id INTO v_lote_id;
    INSERT INTO movimentacoes(lote_id,tipo,quantidade,referencia)
    VALUES (v_lote_id,'ENTRADA',p_quantidade,'RECEBIMENTO '||p_documento);
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO sp_receber;
    RAISE;
  END;

  PROCEDURE pr_dispensar(
    p_item_id IN NUMBER,p_profissional_id IN NUMBER,p_quantidade IN NUMBER) IS
    v_medicamento_id NUMBER; v_solicitada NUMBER; v_ja_dispensada NUMBER;
    v_status VARCHAR2(15); v_prof_ativo CHAR(1);
    v_restante NUMBER; v_retirada NUMBER; v_dispensacao_id NUMBER;
    -- Cursor FEFO: primeiro vencimento mais proximo, lotes vencidos excluidos.
    CURSOR c_lotes(p_med NUMBER) IS
      SELECT lote_id,quantidade_disponivel FROM lotes
       WHERE medicamento_id=p_med AND validade>=TRUNC(SYSDATE)
         AND quantidade_disponivel>0
       ORDER BY validade,lote_id
       FOR UPDATE OF quantidade_disponivel;
  BEGIN
    SAVEPOINT sp_dispensar;
    IF p_quantidade IS NULL OR p_quantidade<=0 OR p_quantidade<>TRUNC(p_quantidade) THEN
      RAISE_APPLICATION_ERROR(-20002,'Quantidade para dispensacao invalida');
    END IF;
    SELECT i.medicamento_id,i.quantidade_solicitada,s.status
      INTO v_medicamento_id,v_solicitada,v_status
      FROM itens_solicitacao i JOIN solicitacoes s
        ON s.solicitacao_id=i.solicitacao_id
     WHERE i.item_id=p_item_id
     FOR UPDATE OF i.quantidade_solicitada;
    SELECT ativo INTO v_prof_ativo FROM profissionais
     WHERE profissional_id=p_profissional_id;
    IF v_prof_ativo<>'S' OR v_status<>'AUTORIZADA' THEN
      RAISE_APPLICATION_ERROR(-20003,'Profissional inativo ou solicitacao nao autorizada');
    END IF;
    SELECT NVL(SUM(quantidade),0) INTO v_ja_dispensada
      FROM dispensacoes WHERE item_id=p_item_id;
    IF v_ja_dispensada+p_quantidade>v_solicitada THEN
      RAISE_APPLICATION_ERROR(-20004,'Quantidade acima do saldo da solicitacao');
    END IF;
    v_restante:=p_quantidade;
    FOR r IN c_lotes(v_medicamento_id) LOOP
      EXIT WHEN v_restante=0;
      v_retirada:=LEAST(r.quantidade_disponivel,v_restante);
      UPDATE lotes SET quantidade_disponivel=quantidade_disponivel-v_retirada
       WHERE lote_id=r.lote_id;
      INSERT INTO dispensacoes(item_id,lote_id,profissional_id,quantidade)
      VALUES (p_item_id,r.lote_id,p_profissional_id,v_retirada)
      RETURNING dispensacao_id INTO v_dispensacao_id;
      INSERT INTO movimentacoes(lote_id,tipo,quantidade,referencia)
      VALUES (r.lote_id,'SAIDA',v_retirada,'DISPENSACAO '||v_dispensacao_id);
      v_restante:=v_restante-v_retirada;
    END LOOP;
    IF v_restante>0 THEN
      RAISE_APPLICATION_ERROR(-20005,'Estoque utilizavel insuficiente; operacao desfeita');
    END IF;
    -- Nao damos COMMIT: a transacao pertence a quem chama o procedimento.
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO sp_dispensar;
    RAISE;
  END;

  PROCEDURE pr_relatorio_vencimentos(p_dias IN NUMBER DEFAULT 30) IS
    CURSOR c_venc IS
      SELECT m.nome,l.codigo_lote,l.validade,l.quantidade_disponivel
        FROM lotes l JOIN medicamentos m ON m.medicamento_id=l.medicamento_id
       WHERE l.quantidade_disponivel>0 AND l.validade<=TRUNC(SYSDATE)+p_dias
       ORDER BY l.validade;
  BEGIN
    DBMS_OUTPUT.PUT_LINE('Lotes vencidos ou com validade em ate '||p_dias||' dias:');
    FOR r IN c_venc LOOP
      DBMS_OUTPUT.PUT_LINE(r.nome||' | '||r.codigo_lote||' | '||
        TO_CHAR(r.validade,'DD/MM/YYYY')||' | Qtd='||r.quantidade_disponivel);
    END LOOP;
  END;
END pkg_farmacia;
