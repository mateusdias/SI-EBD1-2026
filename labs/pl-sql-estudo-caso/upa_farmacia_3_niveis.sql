CREATE TABLE medicamentos (
  medicamento_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome VARCHAR2(100) NOT NULL,
  apresentacao VARCHAR2(100) NOT NULL,
  unidade VARCHAR2(20) NOT NULL,
  estoque_minimo NUMBER(10) DEFAULT 0 NOT NULL,
  ativo CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT ck_medicamento_min CHECK (estoque_minimo >= 0),
  CONSTRAINT ck_medicamento_ativo CHECK (ativo IN ('S','N')),
  CONSTRAINT uq_medicamento UNIQUE (nome, apresentacao)
);
CREATE TABLE fornecedores (
  fornecedor_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  razao_social VARCHAR2(120) NOT NULL UNIQUE,
  cnpj_ficticio VARCHAR2(20) NOT NULL UNIQUE
);
CREATE TABLE profissionais (
  profissional_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome VARCHAR2(100) NOT NULL,
  funcao VARCHAR2(40) NOT NULL,
  ativo CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT ck_prof_ativo CHECK (ativo IN ('S','N'))
);
CREATE TABLE atendimentos (
  atendimento_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  codigo VARCHAR2(20) NOT NULL UNIQUE,
  iniciado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE recebimentos (
  recebimento_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  fornecedor_id NUMBER NOT NULL REFERENCES fornecedores(fornecedor_id),
  documento VARCHAR2(30) NOT NULL,
  recebido_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_receb_doc UNIQUE (fornecedor_id, documento)
);
CREATE TABLE lotes (
  lote_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  medicamento_id NUMBER NOT NULL REFERENCES medicamentos(medicamento_id),
  recebimento_id NUMBER NOT NULL REFERENCES recebimentos(recebimento_id),
  codigo_lote VARCHAR2(35) NOT NULL,
  validade DATE NOT NULL,
  custo_unitario NUMBER(12,2) NOT NULL,
  quantidade_inicial NUMBER(10) NOT NULL,
  quantidade_disponivel NUMBER(10) NOT NULL,
  CONSTRAINT uq_lote UNIQUE (medicamento_id, codigo_lote),
  CONSTRAINT ck_lote_custo CHECK (custo_unitario >= 0),
  CONSTRAINT ck_lote_quantidades CHECK (
    quantidade_inicial > 0 AND quantidade_disponivel >= 0 AND
    quantidade_disponivel <= quantidade_inicial)
);
CREATE TABLE solicitacoes (
  solicitacao_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  atendimento_id NUMBER NOT NULL REFERENCES atendimentos(atendimento_id),
  profissional_id NUMBER NOT NULL REFERENCES profissionais(profissional_id),
  solicitada_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  status VARCHAR2(15) DEFAULT 'AUTORIZADA' NOT NULL,
  CONSTRAINT ck_solicit_status CHECK (status IN ('AUTORIZADA','CANCELADA'))
);
CREATE TABLE itens_solicitacao (
  item_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  solicitacao_id NUMBER NOT NULL REFERENCES solicitacoes(solicitacao_id),
  medicamento_id NUMBER NOT NULL REFERENCES medicamentos(medicamento_id),
  quantidade_solicitada NUMBER(10) NOT NULL,
  CONSTRAINT ck_item_qtd CHECK (quantidade_solicitada > 0),
  CONSTRAINT uq_item_medicamento UNIQUE (solicitacao_id, medicamento_id)
);
CREATE TABLE dispensacoes (
  dispensacao_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  item_id NUMBER NOT NULL REFERENCES itens_solicitacao(item_id),
  lote_id NUMBER NOT NULL REFERENCES lotes(lote_id),
  profissional_id NUMBER NOT NULL REFERENCES profissionais(profissional_id),
  quantidade NUMBER(10) NOT NULL,
  dispensada_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_dispens_qtd CHECK (quantidade > 0)
);
CREATE TABLE movimentacoes (
  movimentacao_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  lote_id NUMBER NOT NULL REFERENCES lotes(lote_id),
  tipo VARCHAR2(15) NOT NULL,
  quantidade NUMBER(10) NOT NULL,
  referencia VARCHAR2(80) NOT NULL,
  ocorrida_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_mov_tipo CHECK (tipo IN ('ENTRADA','SAIDA')),
  CONSTRAINT ck_mov_quantidade CHECK (quantidade > 0)
);
CREATE TABLE auditoria_estoque (
  auditoria_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  lote_id NUMBER NOT NULL REFERENCES lotes(lote_id),
  saldo_anterior NUMBER(10) NOT NULL,
  saldo_novo NUMBER(10) NOT NULL,
  usuario_bd VARCHAR2(128) NOT NULL,
  registrada_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_lotes_fefo ON lotes(medicamento_id, validade);
CREATE INDEX ix_mov_lote ON movimentacoes(lote_id, ocorrida_em);
CREATE INDEX ix_dispens_item ON dispensacoes(item_id);

