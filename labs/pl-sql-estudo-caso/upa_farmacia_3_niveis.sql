CREATE OR REPLACE TRIGGER trg_auditar_saldo
AFTER UPDATE OF quantidade_disponivel ON lotes
FOR EACH ROW
WHEN (OLD.quantidade_disponivel <> NEW.quantidade_disponivel)
BEGIN
  INSERT INTO auditoria_estoque(lote_id,saldo_anterior,saldo_novo,usuario_bd)
  VALUES (:NEW.lote_id,:OLD.quantidade_disponivel,:NEW.quantidade_disponivel,
          SYS_CONTEXT('USERENV','SESSION_USER'));
END;
